export function getTheatreSnapshot(stageIndex: number, profile?: any): TheatreSnapshot {
  const base = THEATRE_SNAPSHOTS[stageIndex] || THEATRE_SNAPSHOTS[0];
  if (!profile || stageIndex < 4) {
    return base;
  }
  const opps = getInvestigatedOpportunitiesForProfile(profile, 4);
  const prim = opps[0] || null;
  const roadmap = prim ? generateDynamicRoadmap(profile, prim) : base.roadmapPhases;

  return {
    ...base,
    rankedCandidates: opps,
    primaryOpportunity: prim,
    roadmapPhases: roadmap,
    activeProfileName: profile?.personal?.name || profile?.name || base.activeProfileName,
  };
}
