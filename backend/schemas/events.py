class EventSeverity(str, Enum):
    INFO = "INFO"
    SUCCESS = "SUCCESS"
    WARNING = "WARNING"
    ERROR = "ERROR"
    CRITICAL = "CRITICAL"


class ScholarXEvent(BaseModel):
    schema_version: int = Field(default=1, description="Event payload contract schema version")
    event_id: str = Field(default_factory=lambda: f"evt-{uuid.uuid4().hex[:12]}")
    session_id: str = Field(..., description="Active session UUID")
    timestamp: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )
    event_type: AgentEventType
    agent_id: str = Field(default="orchestrator", description="Identifier of emitting agent/workflow")
    agent_display_name: str = Field(default="Orchestrator")
    component_type: str = Field(default="AGENT", description="AGENT or WORKFLOW")
    phase: str = Field(default="ORCHESTRATION", description="INTAKE, DISCOVERY, ELIGIBILITY, COST, VERIFICATION, SYNTHESIS, RANKING")
    payload: Dict[str, Any] = Field(default_factory=dict, description="Event-specific metadata")
    related_scholarship_id: Optional[str] = None
    severity: EventSeverity = Field(default=EventSeverity.INFO)

    def to_sse_format(self) -> str:
        """Format as Server-Sent Event payload string"""
        return f"id: {self.event_id}\nevent: {self.event_type.value}\ndata: {self.model_dump_json()}\n\n"
